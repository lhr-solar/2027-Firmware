    def test_reproducible_and_stale_cleanup(self):
        """Identical inputs yield identical files; removed buses leave no stale C."""
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory)
            buses = load_buses([FIXTURE])
            generate(buses, output)
            first = {
                p.relative_to(output): p.read_bytes()
                for p in output.rglob("*")
                if p.is_file()
            }
            time.sleep(1.05)  # Backend timestamps change each second unless removed.
            generate(buses, output)
            self.assertEqual(
                first,
                {
                    p.relative_to(output): p.read_bytes()
                    for p in output.rglob("*")
                    if p.is_file()
                },
            )
            (output / "keep.txt").write_text("not owned by generator")
            generate([], output)
            self.assertFalse((output / "test_bus.c").exists())
            self.assertTrue((output / "keep.txt").exists())

    def test_empty_buses_compile(self):
        """An empty DBC scaffold still produces valid C11 modules."""
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory)
            empty = output / "EmptyBus.dbc"
            empty.write_text("")
            generate(load_buses([empty]), output)
            for source in output.rglob("*.c"):
                subprocess.run(
                    [
                        os.environ.get("CC", "cc"),
                        "-std=c11",
                        "-Wall",
                        "-Wextra",
                        "-Werror",
                        "-pedantic",
                        "-I",
                        str(output),
                        "-c",
                        str(source),
                        "-o",
                        str(output / "empty.o"),
                    ],
                    check=True,
                )

    def test_bad_identifiers(self):
        for identifier in ("int", "_Private", "9Signal"):
            with self.assertRaises(ValueError):
                name(identifier)

    def test_invalid_signal_contracts(self):
        """Fail explicitly for unsupported or unrepresentable conversion contracts."""
        for conversion, length, minimum, maximum in [
            (BaseConversion.factory(0, 0), 8, None, None),
            (BaseConversion.factory(2, 0, is_float=True), 32, None, None),
            (BaseConversion.factory(2, 0), 64, None, None),
            (BaseConversion.factory(1, 0), 8, 300, 400),
        ]:
            with self.assertRaises(ValueError):
                signal_spec(
                    Signal(
                        "Value",
                        0,
                        length,
                        conversion=conversion,
                        minimum=minimum,
                        maximum=maximum,
                    )
                )

    def test_normalized_collisions_fail_before_writing(self):
        with tempfile.TemporaryDirectory() as directory:
            first = Path(directory) / "TestBus.dbc"
            second = Path(directory) / "test_bus.dbc"
            shutil.copy(FIXTURE, first)
            shutil.copy(FIXTURE, second)
            with self.assertRaisesRegex(ValueError, "duplicate C identifier"):
                load_buses([first, second])

    def test_cli(self):
        with tempfile.TemporaryDirectory() as directory:
            result = subprocess.run(
                [
                    sys.executable,
                    str(ROOT / "generate_can_headers.py"),
                    str(FIXTURE),
                    "-o",
                    directory,
                ],
                capture_output=True,
                text=True,
            )
            self.assertEqual(result.returncode, 0, result.stderr)
            result = subprocess.run(
                [
                    sys.executable,
                    str(ROOT / "generate_can_headers.py"),
                    str(Path(directory) / "missing.dbc"),
                    "-o",
                    directory,
                ],
                capture_output=True,
                text=True,
            )
            self.assertEqual(result.returncode, 1)
            self.assertIn("codegen:", result.stderr)


